import { expect } from '@playwright/test'
import { test } from './fixtures/test.js'
import { writeFile } from 'node:fs/promises'
import { checked, expectStock, mutate, operationalFixture, operationalTargetFromEnvironment, selectRemote } from './fixtures/operational.js'

for (const viewport of [{ width: 1280, height: 720 }, { width: 1440, height: 1080 }]) {
  test.describe(`${viewport.width}x${viewport.height}`, () => {
    test.use({ viewport, actionTimeout: 15_000, navigationTimeout: 20_000 })

    test('compra, recibe un lote, reserva, despacha y entrega sin duplicar existencias', async ({ page }, testInfo) => {
      test.setTimeout(180_000)
      page.on('pageerror', (error) => console.error(`Error de navegador: ${error.message}`))
      const f = await operationalFixture(page, operationalTargetFromEnvironment())
      await testInfo.attach('fixture-operativo', { body: JSON.stringify({ reference: f.reference,
        organizationId: f.organizationId, productId: f.productId, warehouseId: f.warehouseId,
        lot: f.lot, expiration: f.expiration }), contentType: 'application/json' })
      const rows = (table: string) => f.api.from(table).select('*').eq('organization_id', f.organizationId)

      await test.step('Compra real desde React, sin existencias previas', async () => {
        expect(await checked(rows('inventory_movements').eq('product_id', f.productId))).toHaveLength(0)
        await page.goto('/compras')
        await page.getByRole('button', { name: 'Registrar compra', exact: true }).click()
        const dialog = page.getByRole('dialog', { name: 'Registrar compra', exact: true })
        await selectRemote(dialog, 'Proveedor', f.reference)
        await dialog.getByLabel('Serie', { exact: false }).fill('F001')
        await dialog.getByLabel('Número', { exact: false }).fill(f.documentNumber)
        await selectRemote(dialog, 'Almacén de recepción', f.reference)
        await selectRemote(dialog, 'Producto 1', f.reference)
        await dialog.getByLabel(/^Cantidad del producto 1/).fill('10')
        await dialog.getByLabel('Costo unitario del producto 1', { exact: true }).fill('10')
        await dialog.getByLabel('Lote del producto 1', { exact: true }).fill(f.lot)
        await dialog.getByLabel('Vencimiento del producto 1', { exact: true }).fill(f.expiration)
        await mutate(page, 'save_purchase_order', () => dialog.getByRole('button', { name: 'Guardar borrador' }).click())
        await expect(dialog).toBeHidden()
      })
      const purchase = await checked(rows('purchase_orders').eq('supplier_id', f.supplierId).single())
      expect(purchase.status).toBe('draft')
      const purchaseRow = page.getByRole('row').filter({ hasText: f.name })

      await test.step('Emisión y recepción inspeccionada del lote', async () => {
        await purchaseRow.getByRole('button', { name: /^Emitir / }).click()
        const emission = page.getByRole('alertdialog', { name: 'Emitir orden de compra' })
        await mutate(page, 'issue_purchase_order', () => emission.getByRole('button', { name: 'Confirmar emisión' }).click())
        await expect(emission).toBeHidden()
        expect((await checked(rows('purchase_orders').eq('id', purchase.id).single())).status).toBe('issued')
        await purchaseRow.getByRole('button', { name: /^Recibir / }).click()
        const dialog = page.getByRole('dialog', { name: 'Registrar recepción' })
        await dialog.getByRole('combobox', { name: 'Ubicación', exact: true }).selectOption(f.locationId)
        await dialog.getByLabel(/^Lote/).fill(f.lot)
        await dialog.getByLabel(/^Vencimiento/).fill(f.expiration)
        await expect(dialog.getByLabel('Cantidad aceptada', { exact: true })).toHaveValue('10')
        await mutate(page, 'receive_purchase_order_partial_inspected', () => dialog.getByRole('button', { name: 'Confirmar recepción' }).click())
        await expect(dialog).toBeHidden()
        expect((await checked(rows('purchase_orders').eq('id', purchase.id).single())).status).toBe('received')
        const receipts = await checked(rows('purchase_receipts').eq('purchase_order_id', purchase.id))
        expect(receipts).toHaveLength(1)
        const items = await checked(rows('purchase_receipt_items').eq('receipt_id', receipts[0].id))
        expect(items).toHaveLength(1)
        expect(items[0]).toMatchObject({ product_id: f.productId, warehouse_id: f.warehouseId,
          location_id: f.locationId, lot: f.lot, expiration_date: f.expiration })
        expect(Number(items[0].quantity)).toBe(10)
        const movements = await checked(rows('inventory_movements').eq('product_id', f.productId))
        expect(movements).toHaveLength(1)
        expect(movements[0]).toMatchObject({ source_type: 'purchase-receipt', source_id: items[0].id,
          movement_type: 'entrada', lot: f.lot, expiration_date: f.expiration })
        expect(Number(movements[0].quantity)).toBe(10)
        await expectStock(f, 10, 0, 10)
        await page.goto('/inventario?vista=lotes')
        await page.getByRole('region', { name: 'Stock por almacén, ubicación y lote' })
          .getByRole('searchbox', { name: 'Buscar', exact: true }).fill(f.reference)
        await expect(page.getByRole('row').filter({ hasText: f.reference }).filter({ hasText: f.lot })).toBeVisible()
      })

      await test.step('Cotización emitida en React', async () => {
        await page.goto('/ventas')
        const newQuote = page.getByRole('button', { name: 'Nueva cotización', exact: true })
        const started = Date.now()
        // Ventas hydrates active customers in 500-row pages before enabling this
        // control. Preserved regression catalogs can exceed the 15s action budget.
        await expect(newQuote).toBeEnabled({ timeout: 45_000 })
        console.info('Ventas: catálogos disponibles en ' + (Date.now() - started) + ' ms')
        await page.keyboard.press('Control+Home')
        await newQuote.click()
        const dialog = page.getByRole('dialog', { name: 'Nueva cotización' })
        await selectRemote(dialog, 'Cliente', f.reference)
        await selectRemote(dialog, 'Producto 1', f.reference)
        await dialog.getByLabel('Cantidad del producto 1', { exact: true }).fill('4')
        await dialog.getByLabel('Precio unitario del producto 1', { exact: true }).fill('25')
        await mutate(page, 'save_sales_quote', () => dialog.getByRole('button', { name: 'Guardar borrador' }).click())
        await expect(dialog).toBeHidden()
        await page.getByRole('row').filter({ hasText: f.name }).getByRole('button', { name: /^Emitir / }).click()
        await mutate(page, 'issue_sales_quote', () => page.getByRole('alertdialog').getByRole('button', { name: 'Emitir cotización', exact: true }).click())
        await expect(page.getByRole('alertdialog')).toBeHidden()
      })
      const quote = await checked(rows('sales_quotes').eq('customer_id', f.customerId).single())
      expect(quote.status).toBe('emitida')

      await test.step('Pedido y reserva FEFO sin reducir stock físico', async () => {
        const trigger = page.getByRole('row').filter({ hasText: f.name }).getByRole('button', { name: 'Crear pedido', exact: true })
        await trigger.click()
        const dialog = page.getByRole('dialog', { name: `Crear pedido ${quote.quote_number}` })
        await expect(dialog).toBeVisible()
        await page.keyboard.press('Escape')
        await expect(dialog).toBeHidden()
        await expect(trigger).toBeFocused()
        await trigger.press('Enter')
        await selectRemote(dialog, 'Almacén de preparación', f.reference)
        await dialog.getByRole('textbox', { name: 'Dirección', exact: true }).fill('Av. Pruebas SILSAN 123, Lima')
        const invalidFields = await dialog.locator('input,select,textarea').evaluateAll((elements) =>
          elements.filter((element) => !(element as HTMLInputElement).validity.valid)
            .map((element) => ({ id: element.id, value: (element as HTMLInputElement).value,
              reason: (element as HTMLInputElement).validationMessage })),
        )
        expect(invalidFields, JSON.stringify(invalidFields)).toEqual([])
        const cancel = dialog.getByRole('button', { name: 'Cancelar', exact: true })
        const confirm = dialog.getByRole('button', { name: 'Confirmar pedido', exact: true })
        await expect(dialog).toBeInViewport({ ratio: 1 })
        await expect(cancel).toBeInViewport({ ratio: 1 })
        await expect(confirm).toBeInViewport({ ratio: 1 })
        await dialog.getByRole('textbox', { name: 'Indicaciones para llegar' }).focus()
        await page.keyboard.press('Tab')
        await expect(cancel).toBeFocused()
        await page.keyboard.press('Tab')
        await expect(confirm).toBeFocused()
        await page.keyboard.press('Tab')
        await expect(dialog.getByRole('button', { name: 'Cerrar', exact: true })).toBeFocused()
        await page.keyboard.press('Shift+Tab')
        await expect(confirm).toBeFocused()
        await page.screenshot({ path: testInfo.outputPath('pedido-viewport.png') })
        await mutate(page, 'create_order_with_fulfillment', () => viewport.height === 720 ? confirm.press('Enter') : confirm.click())
        await expect(dialog).toBeHidden()
        await expectStock(f, 10, 4, 6)
      })
      const order = await checked(rows('orders').eq('source_quote_id', quote.id).single())
      expect(order).toMatchObject({ status: 'confirmado', fulfillment_mode: 'delivery', warehouse_id: f.warehouseId })
      expect((await checked(rows('sales_quotes').eq('id', quote.id).single())).status).toBe('aceptada')
      const orderItem = await checked(rows('order_items').eq('order_id', order.id).single())
      expect(Number(orderItem.quantity)).toBe(4)
      let reservations = await checked(rows('inventory_reservations').eq('product_id', f.productId))
      expect(reservations).toHaveLength(1)
      expect(reservations[0]).toMatchObject({ source_type: 'order-item', source_id: orderItem.id,
        lot: f.lot, expiration_date: f.expiration, status: 'active' })
      expect(Number(reservations[0].quantity)).toBe(4)
      expect(Number(reservations[0].quantity_consumed)).toBe(0)

      await test.step('Venta y despacho físico autorizado desde React', async () => {
        await page.goto('/ventas?vista=ejecucion')
        await page.getByLabel('Buscar', { exact: true }).fill(f.reference)
        await page.getByRole('article').filter({ hasText: order.order_number }).getByRole('button', { name: 'Registrar venta' }).click()
        const saleDialog = page.getByRole('dialog', { name: 'Registrar venta' })
        await saleDialog.getByLabel(/^Comprobante/).selectOption('nota-venta')
        await saleDialog.getByLabel(/^Serie/).fill('NV01')
        await saleDialog.getByLabel(/^Número/).fill(f.documentNumber)
        await mutate(page, 'create_sale_from_order', () => saleDialog.getByRole('button', { name: 'Registrar venta' }).click())
        await expect(saleDialog).toBeHidden()
        await expectStock(f, 10, 4, 6)
        await page.getByRole('article').filter({ hasText: order.order_number }).getByRole('button', { name: 'Despachar bienes' }).click()
        const dispatch = page.getByRole('dialog', { name: 'Despachar venta' })
        await expect(dispatch.getByLabel('Cantidad de esta entrega')).toHaveValue('4')
        await mutate(page, 'dispatch_order_from_reservations', () => dispatch.getByRole('button', { name: 'Confirmar despacho' }).click())
        await expect(dispatch).toBeHidden()
        await expectStock(f, 6, 0, 6)
      })
      const sale = await checked(rows('sales').eq('order_id', order.id).single())
      expect(sale.status).toBe('despachada')
      expect((await checked(rows('orders').eq('id', order.id).single())).fulfillment_status).toBe('dispatched')
      reservations = await checked(rows('inventory_reservations').eq('product_id', f.productId))
      expect(reservations).toHaveLength(1)
      expect(reservations[0].status).toBe('consumed')
      expect(Number(reservations[0].quantity_consumed)).toBe(4)
      const outbound = await checked(rows('inventory_movements').eq('product_id', f.productId).eq('source_type', 'order-dispatch').single())
      expect(outbound).toMatchObject({ reservation_id: reservations[0].id, movement_type: 'salida',
        lot: f.lot, expiration_date: f.expiration, warehouse_id: f.warehouseId, location_id: f.locationId })
      expect(Number(outbound.quantity)).toBe(4)

      await test.step('Distribución asigna la línea al movimiento y lote despachados', async () => {
        await page.goto('/distribucion')
        await page.getByRole('region', { name: 'Pedidos por programar' }).getByLabel('Buscar', { exact: true }).fill(f.reference)
        await page.getByRole('row').filter({ hasText: order.order_number }).getByRole('button', { name: 'Programar envío' }).click()
        const dialog = page.getByRole('dialog', { name: 'Programar entrega', exact: true })
        await expect(dialog).toBeVisible()
        await dialog.getByRole('spinbutton', { name: `Cantidad del lote ${f.lot}`, exact: true }).fill('4')
        await dialog.getByLabel(/^Referencia interna de despacho/).fill(f.reference)
        await dialog.getByLabel(/^Número de guía de remisión/).fill(`T001-${f.documentNumber}`)
        await dialog.locator('summary').filter({ hasText: 'Datos de ruta' }).click()
        await dialog.getByLabel(/^Conductor/).fill('Conductor E2E SILSAN')
        await dialog.getByLabel(/^Vehículo/).fill('Vehículo E2E')
        await dialog.getByLabel(/^Placa/).fill('E2E-123')
        await mutate(page, 'save_distribution_delivery', () => dialog.getByRole('button', { name: 'Programar entrega' }).click())
        await expect(dialog).toBeHidden()
        await expectStock(f, 6, 0, 6)
      })
      const delivery = await checked(rows('distribution_deliveries').eq('order_id', order.id).single())
      expect(delivery.delivery_status).toBe('programado')
      const allocations = await checked(rows('distribution_delivery_inventory_allocations').eq('delivery_id', delivery.id))
      expect(allocations).toHaveLength(1)
      expect(allocations[0]).toMatchObject({ order_id: order.id, order_line_id: orderItem.id,
        inventory_movement_id: outbound.id })
      expect(Number(allocations[0].quantity)).toBe(4)
      const deliveryItems = await checked(rows('distribution_delivery_items').eq('delivery_id', delivery.id))
      expect(deliveryItems).toHaveLength(1)
      expect(deliveryItems[0].order_line_id).toBe(orderItem.id)
      expect(Number(deliveryItems[0].quantity)).toBe(4)

      await test.step('Editar planificación tiene nombre accesible y cierre por teclado', async () => {
        await page.goto('/distribucion?vista=seguimiento')
        await page.getByRole('searchbox', { name: 'Buscar', exact: true }).fill(order.order_number)
        const article = page.getByRole('article').filter({ hasText: order.order_number }).filter({ hasText: f.name })
        const edit = article.getByRole('button', { name: 'Editar planificación', exact: true })
        await edit.click()
        const editDialog = page.getByRole('dialog', { name: 'Editar planificación', exact: true })
        await expect(editDialog).toBeVisible()
        await page.keyboard.press('Escape')
        await expect(editDialog).toBeHidden()
      })

      await test.step('Traslado y conformidad completa del cliente desde React', async () => {
        await page.goto('/distribucion?vista=seguimiento')
        await page.getByRole('searchbox', { name: 'Buscar', exact: true }).fill(order.order_number)
        const article = page.getByRole('article').filter({ hasText: order.order_number }).filter({ hasText: f.name })
        for (const [action, status] of [['Iniciar preparación', 'preparando'], ['Iniciar traslado', 'en_curso'], ['Marcar en destino', 'en_destino']]) {
          await mutate(page, 'save_distribution_delivery', () => article.getByRole('button', { name: action, exact: true }).click())
          await expect.poll(async () => (await checked(rows('distribution_deliveries').eq('id', delivery.id).single())).delivery_status).toBe(status)
        }
        await article.getByRole('button', { name: 'Registrar resultado', exact: true }).click()
        const dialog = page.getByRole('dialog', { name: 'Registrar resultado de entrega' })
        // A real partial receipt enables rescheduling without bypassing state rules.
        await dialog.getByLabel('Recibido ahora', { exact: true }).fill('2')
        await dialog.getByLabel(/^Evidencia o constancia/).fill(`Parcial ${f.reference}`)
        await mutate(page, 'record_distribution_delivery_outcome', () => dialog.getByRole('button', { name: 'Confirmar entrega parcial' }).click())
        await expect(dialog).toBeHidden()
        await expect.poll(async () => (await checked(rows('distribution_deliveries').eq('id', delivery.id).single())).delivery_status).toBe('entrega_parcial')
        await article.getByRole('button', { name: 'Reprogramar fecha', exact: true }).press('Enter')
        const rescheduleDialog = page.getByRole('dialog', { name: 'Reprogramar entrega', exact: true })
        await expect(rescheduleDialog).toBeVisible()
        await rescheduleDialog.getByRole('textbox', { name: 'Motivo de reprogramación' }).fill('Comprobación de teclado sin guardar cambios')
        await page.keyboard.press('Tab')
        const cancel = rescheduleDialog.getByRole('button', { name: 'Cancelar', exact: true })
        await expect(cancel).toBeFocused()
        await cancel.press('Enter')
        await expect(rescheduleDialog).toBeHidden()
        await article.getByRole('button', { name: 'Registrar recepción adicional', exact: true }).click()
        await dialog.getByLabel('Recibido ahora', { exact: true }).fill('2')
        await dialog.getByLabel(/^Evidencia o constancia/).fill(`Conformidad ${f.reference}`)
        await mutate(page, 'record_distribution_delivery_outcome', () => dialog.getByRole('button', { name: 'Confirmar entrega completa' }).click())
        await expect(dialog).toBeHidden()
        await page.reload()
        await page.getByRole('searchbox', { name: 'Buscar', exact: true }).fill(order.order_number)
        await expect(article).toContainText(/entregado/i)
      })

      await test.step('Conservación final y unicidad de todos los documentos', async () => {
        await expectStock(f, 6, 0, 6)
        expect((await checked(rows('distribution_deliveries').eq('id', delivery.id).single())).delivery_status).toBe('entregado')
        expect((await checked(rows('orders').eq('id', order.id).single())).fulfillment_status).toBe('delivered')
        expect((await checked(rows('sales').eq('id', sale.id).single())).status).toBe('despachada')
        const outcomes = await checked(rows('distribution_delivery_outcomes').eq('delivery_id', delivery.id))
        expect(outcomes).toHaveLength(2)
        expect(outcomes.filter((outcome) => outcome.result_status === 'entrega_parcial')).toHaveLength(1)
        const complete = outcomes.find((outcome) => outcome.result_status === 'entregado')!
        expect(complete).toMatchObject({ result_status: 'entregado', evidence: `Conformidad ${f.reference}` })
        const outcomeLines = await checked(rows('distribution_delivery_outcome_lines').in('outcome_id', outcomes.map((outcome) => outcome.id)))
        expect(outcomeLines).toHaveLength(2)
        expect(outcomeLines.every((line) => line.order_line_id === orderItem.id)).toBe(true)
        expect(outcomeLines.reduce((sum, line) => sum + Number(line.quantity_delivered), 0)).toBe(4)
        for (const [table, column, value] of [
          ['purchase_orders', 'supplier_id', f.supplierId], ['purchase_receipts', 'purchase_order_id', purchase.id],
          ['sales_quotes', 'customer_id', f.customerId], ['orders', 'source_quote_id', quote.id],
          ['sales', 'order_id', order.id], ['inventory_reservations', 'product_id', f.productId],
          ['distribution_deliveries', 'order_id', order.id], ['distribution_delivery_items', 'delivery_id', delivery.id],
          ['distribution_delivery_inventory_allocations', 'delivery_id', delivery.id],
        ]) expect(await checked(rows(table).filter(column, 'eq', value)), table).toHaveLength(1)
        const movements = await checked(rows('inventory_movements').eq('product_id', f.productId))
        expect(movements).toHaveLength(2)
        expect(movements.map((movement) => movement.id)).toEqual(expect.arrayContaining([outbound.id]))
        expect(movements.reduce((sum, movement) => sum + (movement.movement_type === 'entrada' ? 1 : -1) * Number(movement.quantity), 0)).toBe(6)
        const evidencePath = testInfo.outputPath('operational-evidence.json')
        await writeFile(evidencePath, JSON.stringify({ reference: f.reference, organizationId: f.organizationId,
          productId: f.productId, warehouseId: f.warehouseId, lot: f.lot, expiration: f.expiration,
          physical: 6, reserved: 0, available: 6, received: 10, dispatched: 4, delivered: 4,
          purchaseId: purchase.id,
          quoteId: quote.id, orderId: order.id, orderItemId: orderItem.id, reservationId: reservations[0].id,
          outboundMovementId: outbound.id, deliveryId: delivery.id, outcomeId: complete.id }, null, 2))
        await testInfo.attach('trazabilidad-operativa', { path: evidencePath, contentType: 'application/json' })
      })
    })
  })
}
